export const GEMINI_LANGUAGE_CODES = new Set<string>(GEMINI_LANGUAGE_OPTIONS.map(([code]) => code));

export function getLanguageOptions(method: LyricsMethod): ReadonlyArray<readonly [string, string]> {
  return method === "local" ? WHISPER_LANGUAGE_OPTIONS : GEMINI_LANGUAGE_OPTIONS;
}

const WHISPER_CODE_ALIASES: Readonly<Record<string, string>> = {
  cmn: "zh",
  fil: "tl",
  nb: "no",
  jv: "jw",
};
function whisperCode(code: string) {
  const base = code.split("-")[0];
  return WHISPER_CODE_ALIASES[base] ?? base;
}

/** Preserve exact selections; translate provider codes only when switching method. */
export function resolveLanguageCode(method: LyricsMethod, code: string): string {
  const supported = method === "local" ? WHISPER_LANGUAGE_CODES : GEMINI_LANGUAGE_CODES;
  if (supported.has(code)) return code;
  const localCode = whisperCode(code);
  if (method === "local") return supported.has(localCode) ? localCode : "";
  return (
    GEMINI_LANGUAGE_OPTIONS.find(([candidate]) => whisperCode(candidate) === localCode)?.[0] ?? ""
  );
}
